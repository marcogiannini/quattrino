/**
 * Traduzioni dell'interfaccia (italiano e inglese). La lingua deriva dall'impostazione
 * `locale` dei dati (it-IT, en-GB…), quindi segue l'utente su tutti i dispositivi sincronizzati.
 * L'italiano è il catalogo di riferimento: il tipo dell'inglese obbliga a tradurre ogni chiave.
 */

export type Lang = 'it' | 'en';
export const LANGUAGES: { lang: Lang; locale: string; label: string }[] = [
  { lang: 'it', locale: 'it-IT', label: 'Italiano' },
  { lang: 'en', locale: 'en-GB', label: 'English' },
];

export const langOf = (locale: string): Lang => (locale.toLowerCase().startsWith('en') ? 'en' : 'it');

/** Lingua iniziale per una nuova installazione: italiano se il browser/sistema è in italiano, altrimenti inglese. */
export function detectLocale(language: string | undefined = typeof navigator === 'undefined' ? undefined : navigator.language): string {
  return (language ?? 'it').toLowerCase().startsWith('it') ? 'it-IT' : 'en-GB';
}

