const catalogs: Record<Lang, Record<Key, string>> = { it, en };

export type TFn = (key: Key, params?: Record<string, string | number>) => string;

export function translator(lang: Lang): TFn {
  const cat = catalogs[lang];
  return (key, params) => {
    const s = cat[key];
    return params ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`)) : s;
  };
}

/** Nome da mostrare: le categorie predefinite non rinominate si traducono, le altre restano come scritte. */
export function categoryName(t: TFn, c: Pick<Category, 'id' | 'name' | 'builtin'> | undefined): string {
  if (!c) return t('common.removedCategory');
  if (c.builtin && c.id.startsWith('cat-')) {
    const key = `cat.${c.id.slice(4)}` as Key;
    if (key in it && c.name === it[key]) return t(key);
  }
  return c.name;
}

/** Nomi accettati nell'importazione CSV per le categorie predefinite (italiano e inglese). */
export function builtinAliases(): Map<string, string> {
  const out = new Map<string, string>();
  for (const k of Object.keys(it) as Key[]) {
    if (!k.startsWith('cat.')) continue;
    const id = `cat-${k.slice(4)}`;
    out.set(it[k], id);
    out.set(en[k], id);
  }
  return out;
}

